ALTER TABLE "Business" ALTER COLUMN "type" TYPE TEXT;
DROP TYPE "BusinessType";
CREATE TYPE "BusinessType" AS ENUM ('INDEPENDENT_SUPPLIER', 'WHOLESALE_TRADER');
ALTER TABLE "Business" ALTER COLUMN "type" TYPE "BusinessType" USING (
  CASE "type"::text
    WHEN 'FACTORY' THEN 'INDEPENDENT_SUPPLIER'::"BusinessType"
    WHEN 'COMPANY' THEN 'INDEPENDENT_SUPPLIER'::"BusinessType"
    WHEN 'SUPPLIER' THEN 'INDEPENDENT_SUPPLIER'::"BusinessType"
    WHEN 'IMPORTER' THEN 'INDEPENDENT_SUPPLIER'::"BusinessType"
    WHEN 'WHOLESALE_TRADER' THEN 'WHOLESALE_TRADER'::"BusinessType"
  END
);